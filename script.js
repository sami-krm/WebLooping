const ctr = g => ({ x: g.x + g.w / 2, y: g.y + g.h / 2 });
function exitPt(g, ox, oy, dx, dy) {
  if (g.shape === 'circle' || g.shape === 'diamond' || g.shape === 'tri' || g.shape === 'none') { const c = ctr(g), r = g.shape === 'none' ? 0 : g.w / 2 * (g.shape === 'diamond' ? 0.85 : 1); return { x: c.x + dx * r, y: c.y + dy * r }; }
  let t = Infinity;
  if (dx > 1e-9) t = Math.min(t, (g.x + g.w - ox) / dx); if (dx < -1e-9) t = Math.min(t, (g.x - ox) / dx);
  if (dy > 1e-9) t = Math.min(t, (g.y + g.h - oy) / dy); if (dy < -1e-9) t = Math.min(t, (g.y - oy) / dy);
  if (!isFinite(t) || t < 0) t = 0; return { x: ox + dx * t, y: oy + dy * t };
}
function segment(ga, gb, off = 0) {
  const a = ctr(ga), b = ctr(gb); let dx = b.x - a.x, dy = b.y - a.y; const d = Math.hypot(dx, dy) || 1; dx /= d; dy /= d;
  const px = -dy * off, py = dx * off;
  const p1 = exitPt(ga, a.x + px, a.y + py, dx, dy), p2 = exitPt(gb, b.x + px, b.y + py, -dx, -dy);
  return { p1, p2, dx, dy, nx: -dy, ny: dx };
}
