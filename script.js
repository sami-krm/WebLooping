function exportSVGString() {
  const { svg, bbox } = buildContent(true); const b = bbox;
  return { w: Math.ceil(b.w), h: Math.ceil(b.h), svg: `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${Math.ceil(b.w)}" height="${Math.ceil(b.h)}" viewBox="${b.x} ${b.y} ${b.w} ${b.h}"><rect x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" fill="${S().colors.canvasBg}"/>${svg}</svg>` };
}
async function pngBlob(scale = 2) {
  const s = exportSVGString(); const img = new Image();
  img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(s.svg); await img.decode();
  const cv = document.createElement('canvas'); cv.width = s.w * scale; cv.height = s.h * scale; const cx = cv.getContext('2d'); cx.scale(scale, scale); cx.drawImage(img, 0, 0, s.w, s.h);
  return await new Promise(r => cv.toBlob(r, 'image/png'));
}
const fileBase = () => normId(M.name || 'modele');
async function doAct(a) {
  document.querySelectorAll('details.menu').forEach(d => d.open = false);
  if (a === 'new') confirmModal('Créer un nouveau modèle vide ? Le modèle actuel sera remplacé (vous pourrez annuler avec Ctrl+Z).', () => { pushUndo(); const st = M.settings; M = emptyModel(); M.settings = st; sel = null; afterLoad(true); });
  else if (a === 'example') confirmModal('Charger le modèle d\'exemple ? Le modèle actuel sera remplacé (annulable avec Ctrl+Z).', () => { pushUndo(); M = exampleModel(); sel = null; afterLoad(true); });
  else if (a === 'open') $('#fileModel').click();
  else if (a === 'save') download(fileBase() + '.looping.json', JSON.stringify(M, null, 1), 'application/json');
  else if (a === 'undo') undo(); else if (a === 'redo') redo();
  else if (a === 'svg') download(fileBase() + '.svg', exportSVGString().svg, 'image/svg+xml');
  else if (a === 'png') { try { download(fileBase() + '.png', await pngBlob(2)); } catch (e) { toast('Export PNG impossible : ' + e.message); } }
  else if (a === 'copyimg') {
    try { const b = await pngBlob(2); await navigator.clipboard.write([new ClipboardItem({ 'image/png': b })]); toast('Image copiée dans le presse-papiers'); }
    catch (e) { toast('Copie d\'image refusée par le navigateur : image téléchargée à la place'); try { download(fileBase() + '.png', await pngBlob(2)); } catch (_) { } }
  }
  else if (a === 'sqlfile') { const mld = buildMLD(); download(fileBase() + '_' + S().dbms + '.sql', genSQL(mld, S().dbms), 'application/sql'); }
  else if (a === 'sqlall') { const mld = buildMLD(); const keys = [...Object.keys(DIALECTS), 'custom']; download(fileBase() + '_tous_SGBD.sql', keys.map(k => genSQL(mld, k)).join('\n\n\n'), 'application/sql'); }
  else if (a === 'copysql') { copyText(genSQL(buildMLD(), S().dbms)); }
  else if (a === 'mldtxt') { download(fileBase() + '_MLD.txt', mldText(buildMLD())); }
  else if (a === 'custom') customModal();
  else if (a === 'style') styleModal();
}

