function buildMLD() {
  const warnings = [], notes = [];
  const ents = M.nodes.filter(n => n.type === 'entity'), assocs = M.nodes.filter(n => n.type === 'assoc');
  // --- héritages
  const childInfo = {}, absorbed = {}, droppedParent = {}, absorbedChildren = {};
  for (const hN of M.nodes.filter(n => n.type === 'inherit')) {
    const par = M.links.find(l => l.kind === 'inhP' && l.from === hN.id), kids = M.links.filter(l => l.kind === 'inhC' && l.from === hN.id).map(l => l.to);
    if (!par) { warnings.push('Un héritage n\'a pas d\'entité mère.'); continue; }
    if (!kids.length) warnings.push(`L'héritage de ${N(par.to)?.name} n'a aucune entité fille.`);
    for (const k of kids) childInfo[k] = { parent: par.to, mode: hN.mode || 'child', inh: hN };
    if (hN.mode === 'parent') { for (const k of kids) { absorbed[k] = par.to; (absorbedChildren[par.to] = absorbedChildren[par.to] || []).push(k); } }
    if (hN.mode === 'children') droppedParent[par.to] = true;
  }
  const resolve = id => { let i = 0; while (absorbed[id] && i++ < 20) id = absorbed[id]; return id; };
  const generated = id => { const e = N(id); return e && e.type === 'entity' && !e.fictive && !droppedParent[id] && !absorbed[id]; };
  // --- classification des associations
  const max1 = l => l.card.endsWith('1');
  const migr = [], tabAssoc = [];
  for (const a of assocs) {
    const legs = legsOf(a.id).filter(l => N(l.to) && N(l.to).type === 'entity');
    if (legs.length < 2) { warnings.push(`L'association « ${a.name} » doit être reliée à au moins deux pattes.`); continue; }
    if (legs.length === 2 && (max1(legs[0]) || max1(legs[1]))) {
      let recv; if (max1(legs[0]) && max1(legs[1])) recv = legs[1].card === '1,1' && legs[0].card !== '1,1' ? legs[1] : legs[0]; else recv = max1(legs[0]) ? legs[0] : legs[1];
      const other = recv === legs[0] ? legs[1] : legs[0];
      migr.push({ a, recv, other, both: max1(legs[0]) && max1(legs[1]) });
    } else tabAssoc.push({ a, legs });
    for (const l of legs) if (l.relative && l.card !== '1,1') warnings.push(`Identifiant relatif sur « ${a.name} » : la cardinalité devrait être 1,1.`);
  }
  // --- clés
  const keyMemo = {}, visiting = new Set();
  const ownIds = e => e.props.filter(p => p.id).map(p => ({ name: p.name, type: p.type, p1: p.p1, p2: p.p2 }));
  function keyOf(id) {
    id = resolve(id); if (keyMemo[id]) return keyMemo[id];
    const e = N(id); if (!e) return [];
    if (visiting.has(id)) { warnings.push(`Cycle d'identification détecté autour de ${e.name}.`); return ownIds(e); }
    visiting.add(id); let cols = [];
    const ci = childInfo[id];
    if (ci && ci.mode === 'children') cols.push(...ownIds(N(ci.parent)));
    else if (ci && ci.mode === 'child' && !e.props.some(p => p.id)) cols.push(...keyOf(ci.parent));
    cols.push(...ownIds(e));
    for (const m of migr) if (m.recv.to === id && m.recv.relative) cols.push(...keyOf(m.other.to).map(c => ({ ...c, name: m.other.role ? c.name + '_' + m.other.role : c.name })));
    visiting.delete(id); keyMemo[id] = cols; return cols;
  }
  // --- construction des tables
  const tables = [], byEnt = {};
  const tnames = new Set();
  const newTable = (name, src, kind) => { let n = name || 'table', i = 2; while (tnames.has(n.toLowerCase())) n = name + '_' + i++; tnames.add(n.toLowerCase()); const T = { name: n, src, kind, cols: [], fks: [], uniques: [], comments: [] }; tables.push(T); return T; };
  const colName = (T, base) => { let n = base, i = 2; while (T.cols.some(c => c.name.toLowerCase() === n.toLowerCase())) n = base + '_' + i++; return n; };
  const addProp = (T, p, o = {}) => { T.cols.push({ name: colName(T, p.name), type: p.type, p1: p.p1, p2: p.p2, pk: o.pk ?? !!p.id, nn: o.nn ?? (p.nn || p.id), uniq: !!p.uniq && !(o.pk ?? p.id), def: p.def || '' }); };
  const addFK = (T, entId, o) => {
    const tgt = resolve(entId), keys = keyOf(tgt), names = [];
    if (!keys.length) warnings.push(`L'entité ${N(tgt)?.name || '?'} n'a pas d'identifiant : référence impossible depuis ${T.name}.`);
    for (const k of keys) {
      const nm = colName(T, o.role ? k.name + '_' + o.role : k.name); names.push(nm);
      T.cols.push({ name: nm, type: k.type === 'COUNTER' ? 'INT' : k.type, fromCounter: k.type === 'COUNTER', p1: k.p1, p2: k.p2, pk: !!o.pk, nn: !!(o.nn || o.pk), uniq: false, fk: true, fkPlain: !generated(tgt), def: '' });
    }
    if (names.length) {
      if (generated(tgt)) T.fks.push({ cols: names, ref: tgt, refCols: keys.map(k => k.name) });
      else if (droppedParent[tgt]) T.comments.push(`${names.join(', ')} : référence vers ${N(tgt).name} (entité mère non générée).`);
      if (o.uniq) T.uniques.push(names);
    }
    return names;
  };
  for (const e of ents) {
    if (!generated(e.id)) continue;
    const T = newTable(e.name, e.id, 'entity'); byEnt[e.id] = T;
    const ci = childInfo[e.id];
    if (ci && ci.mode === 'children') { for (const p of N(ci.parent).props) addProp(T, p); }
    else if (ci && ci.mode === 'child' && !e.props.some(p => p.id)) addFK(T, ci.parent, { pk: true, nn: true });
    if (!e.props.some(p => p.id) && !ci && !migr.some(m => m.recv.to === e.id && m.recv.relative)) warnings.push(`L'entité ${e.name} n'a pas d'identifiant.`);
    for (const p of e.props) addProp(T, p);
    for (const m of migr) if (m.recv.to === e.id && m.recv.relative) addFK(T, m.other.to, { pk: true, nn: true, role: m.other.role });
    const kids = absorbedChildren[e.id];
    if (kids && kids.length) {
      for (const k of kids) for (const p of N(k).props) addProp(T, p, { pk: false, nn: false });
      T.cols.push({ name: colName(T, 'type_' + e.name.toLowerCase()), type: 'VARCHAR', p1: 30, pk: false, nn: true, uniq: false, def: '' });
      T.comments.push(`Entités filles absorbées : ${kids.map(k => N(k).name).join(', ')} (colonne discriminante type_${e.name.toLowerCase()}).`);
    }
  }
  if (ents.length > 1) { const seen = {}; for (const e of ents) { const k = (e.name || '').toLowerCase(); if (seen[k]) warnings.push(`Deux entités portent le nom « ${e.name} ».`); seen[k] = 1; } }
  // migrations de clés étrangères (associations x,1)
  for (const m of migr) {
    if (m.recv.relative) { for (const p of m.a.props) { const T = byEnt[resolve(m.recv.to)]; if (T) addProp(T, p, { pk: false }); } continue; }
    const r = resolve(m.recv.to), T = byEnt[r];
    if (!T) { if (N(m.recv.to)?.fictive) notes.push(`« ${m.a.name} » : pas de migration (entité fictive ${N(m.recv.to).name}).`); else if (droppedParent[m.recv.to]) warnings.push(`« ${m.a.name} » vise l'entité mère ${N(m.recv.to).name} qui n'est pas générée.`); continue; }
    const nn = m.recv.card === '1,1' && r === m.recv.to;
    addFK(T, m.other.to, { pk: false, nn, role: m.other.role || m.recv.role, uniq: m.both });
    for (const p of m.a.props) addProp(T, p, { pk: false, nn: p.nn && nn });
  }
  // contraintes CIF
  const cifTargets = {};
  for (const c of M.nodes.filter(n => n.type === 'constraint' && n.kind === 'CIF')) {
    const ls = M.links.filter(l => l.kind === 'cons' && l.from === c.id);
    const as = ls.filter(l => N(l.to)?.type === 'assoc').map(l => l.to), tg = ls.filter(l => l.target && N(l.to)?.type === 'entity').map(l => l.to);
    for (const a of as) { cifTargets[a] = cifTargets[a] || new Set(); tg.forEach(t => cifTargets[a].add(t)); }
  }
  // associations porteuses de table
  for (const { a, legs } of tabAssoc) {
    const T = newTable(a.name, a.id, 'assoc');
    const count = {}; legs.forEach(l => count[l.to] = (count[l.to] || 0) + 1); const seen = {};
    for (const l of legs) {
      if (childInfo[l.to]?.mode !== 'children' && droppedParent[l.to]) { }
      seen[l.to] = (seen[l.to] || 0) + 1;
      const role = l.role || (count[l.to] > 1 && seen[l.to] > 1 ? String(seen[l.to]) : '');
      const inPk = !(legs.length > 2 && max1(l)) && !(cifTargets[a.id] && cifTargets[a.id].has(l.to));
      addFK(T, l.to, { pk: inPk, nn: true, role });
    }
    for (const p of a.props) addProp(T, p, { pk: !!p.id });
    if (!T.cols.some(c => c.pk)) T.cols.forEach(c => { if (c.fk) c.pk = true; });
  }
  // contraintes inter-associations
  const KN = { X: 'exclusion', T: 'totalité', XT: 'partition', S: 'simultanéité', I: 'inclusion', '=': 'égalité', CIF: 'CIF' };
  for (const c of M.nodes.filter(n => n.type === 'constraint' && n.kind !== 'CIF')) {
    const ls = M.links.filter(l => l.kind === 'cons' && l.from === c.id).map(l => N(l.to)?.name).filter(Boolean);
    notes.push(`Contrainte d'${KN[c.kind] || c.kind} (${c.kind}) entre ${ls.join(', ') || '—'}${c.label ? ' — ' + c.label : ''} : à implémenter (déclencheur ou règle de gestion).`);
  }
  // nom des tables référencées
  for (const T of tables) for (const f of T.fks) f.refTable = byEnt[f.ref]?.name || '?';
  const rules = M.nodes.filter(n => n.type === 'rule');
  return { tables, warnings: [...new Set(warnings)], notes, rules };
}

